'use strict';

const fs = require('fs');
const path = require('path');
const espree = require('espree');

const root = path.join(__dirname, '..');
const outputDir = path.join(root, '.pisi-types');
const outputPath = path.join(outputDir, 'runtime-globals.d.ts');

function readJson(relativePath) {
    return JSON.parse(fs.readFileSync(path.join(root, relativePath), 'utf8'));
}

function collectManifestBindings(relativePath) {
    const manifest = readJson(relativePath);
    return manifest.flatMap((entry) => entry.bindings || []);
}

function collectPatternNames(pattern, names) {
    if (!pattern) return;
    if (pattern.type === 'Identifier') {
        names.add(pattern.name);
        return;
    }
    if (pattern.type === 'RestElement') {
        collectPatternNames(pattern.argument, names);
        return;
    }
    if (pattern.type === 'AssignmentPattern') {
        collectPatternNames(pattern.left, names);
        return;
    }
    if (pattern.type === 'ArrayPattern') {
        pattern.elements.forEach((item) => collectPatternNames(item, names));
        return;
    }
    if (pattern.type === 'ObjectPattern') {
        pattern.properties.forEach((property) => {
            collectPatternNames(property.value || property.argument, names);
        });
    }
}

function walkSourceFiles(relativeDir, extensions = new Set(['.js', '.mjs'])) {
    const start = path.join(root, relativeDir);
    if (!fs.existsSync(start)) return [];
    const files = [];
    const queue = [start];

    while (queue.length) {
        const current = queue.shift();
        for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
            const fullPath = path.join(current, entry.name);
            if (entry.isDirectory()) {
                queue.push(fullPath);
                continue;
            }
            if (extensions.has(path.extname(entry.name))) {
                files.push(fullPath);
            }
        }
    }

    return files;
}

function collectDynamicGlobalProperties() {
    const names = new Set();
    const files = [...walkSourceFiles('renderer'), ...walkSourceFiles('main'), path.join(root, 'preload.js')].filter((filePath) => fs.existsSync(filePath));

    const assignmentPattern = /\b(?:window|globalThis)\.([A-Za-z_$][\w$]*)\s*(?:=|\|\|=|\?\?=)/g;
    const definePattern = /Object\.defineProperty\(\s*(?:window|globalThis)\s*,\s*['"]([A-Za-z_$][\w$]*)['"]/g;

    for (const filePath of files) {
        const source = fs.readFileSync(filePath, 'utf8');
        for (const pattern of [assignmentPattern, definePattern]) {
            pattern.lastIndex = 0;
            let match;
            while ((match = pattern.exec(source)) !== null) {
                names.add(match[1]);
            }
        }
    }

    return [...names];
}

function collectRendererStateBridges() {
    const filePath = path.join(root, 'renderer/core/state.mjs');
    if (!fs.existsSync(filePath)) return [];

    const source = fs.readFileSync(filePath, 'utf8');
    const match = source.match(/\[([\s\S]*?)\]\.forEach\(definePisiStateBridge\)/);
    if (!match) return [];

    return [...match[1].matchAll(/['"]([A-Za-z_$][\w$]*)['"]/g)].map((item) => item[1]);
}

function collectRuntimeGlobals(relativePath) {
    const source = fs.readFileSync(path.join(root, relativePath), 'utf8');
    const ast = espree.parse(source, {
        ecmaVersion: 'latest',
        sourceType: 'module'
    });
    const names = new Set();

    for (const statement of ast.body) {
        if (statement.type === 'VariableDeclaration') {
            for (const declaration of statement.declarations) {
                collectPatternNames(declaration.id, names);
            }
        } else if (statement.type === 'FunctionDeclaration' && statement.id?.name) {
            names.add(statement.id.name);
        }
    }

    return [...names];
}

function isIdentifier(name) {
    return /^[A-Za-z_$][\w$]*$/.test(name);
}

const names = new Set([
    ...collectManifestBindings('renderer/module-manifest.json'),
    ...collectManifestBindings('main/module-manifest.json'),
    ...collectRuntimeGlobals('main/runtime.js'),
    ...collectDynamicGlobalProperties(),
    ...collectRendererStateBridges()
]);

const declarations = [...names]
    .filter(isIdentifier)
    .sort((left, right) => left.localeCompare(right))
    .map((name) => ['// @ts-ignore runtime-owned global generated from Pisi ownership metadata', `declare var ${name}: any;`].join('\n'))
    .join('\n');

const content = `// Generated by scripts/generate-checkjs-globals.js.
// This file exists only for JavaScript type checking. Runtime ownership is
// still enforced by the Pisi module registries and architecture audit.

interface Window {
    [key: string]: any;
}

${declarations}
`;

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputPath, content, 'utf8');

console.log(`Generated checkJs globals for ${names.size} runtime-owned identifiers.`);
